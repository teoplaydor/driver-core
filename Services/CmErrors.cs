        public static string Describe(int code)
        {
            return Text.TryGetValue(code, out var s) ? s : $"Код проблемы {code}";
        }

        /// <summary>Перевод кода диспетчера устройств в состояние для интерфейса.</summary>
        public static DeviceHealth Classify(int code)
        {
            switch (code)
            {
                case 0:
                    return DeviceHealth.Ok;
                case 22:
                case 32:
                case 44:
                case 48:
                    return DeviceHealth.Disabled;
                case 24:
                case 45:
                    return DeviceHealth.NotConnected;
                case 1:
                case 18:
                case 28:
                case 31:
                case 37:
                case 39:
                case 52:
                    return DeviceHealth.NeedsDriver;
                default:
                    return DeviceHealth.Error;
            }
        }
